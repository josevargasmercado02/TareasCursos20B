import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

# Load the data again within this cell to ensure correct processing
ref = pd.read_excel("Datos estaciones AMB PM2.5.xlsx")
cal = pd.read_excel("pm25_sensor.xlsx")

# Ensure time columns are datetime
ref["fecha_hora_med"] = pd.to_datetime(ref["fecha_hora_med"], errors="coerce")
cal["time"] = pd.to_datetime(cal["time"], errors="coerce")

# Handle non-numeric values in 'pm25' columns
# Replace 'NoData' with NaN before converting to numeric
ref['PM2.5'] = ref['PM2.5'].replace('NoData', np.nan)
cal['pm25'] = cal['pm25'].replace('NoData', np.nan)

ref['PM2.5'] = pd.to_numeric(ref['PM2.5'], errors='coerce')
cal['pm25'] = pd.to_numeric(cal['pm25'], errors='coerce')

# Set time columns as index
ref = ref.set_index("fecha_hora_med")
cal = cal.set_index("time")

# Define the common range and filter by index
inicio = "2018-11-03"
fin = "2019-08-31"

df_ref = ref[(ref.index >= inicio) & (ref.index <= fin)].copy()
df_sensor = cal[(cal.index >= inicio) & (cal.index <= fin)].copy()


# === 1. Asegurar que los índices de tiempo estén sin tz ===
# Already handled by setting index and filtering within this cell

# === 2. Resample a 30 minutos (base común más fina) y merge ===
df_ref_res   = df_ref.resample("30min").mean().rename(columns={"PM2.5": "pm25_ref"})
df_sens_res  = df_sensor.resample("30min").mean().rename(columns={"pm25": "pm25_cal"})

# Remove timezone information before concatenation
df_ref_res.index = df_ref_res.index.tz_localize(None)
df_sens_res.index = df_sens_res.index.tz_localize(None)


df_merged = pd.concat([df_ref_res, df_sens_res], axis=1).dropna(how="any")

# === 3. Distancia euclídea total y por día ===
diff = df_merged["pm25_ref"] - df_merged["pm25_cal"]
euclid_total = np.sqrt(np.nansum(diff**2))
print(f"Distancia euclídea TOTAL (sin rolling): {euclid_total:.4f}")

df_merged["date"] = df_merged.index.date
dist_by_day = (
    df_merged.dropna(subset=["pm25_ref","pm25_cal"])
    .groupby("date")
    .apply(lambda g: np.sqrt(np.nansum((g["pm25_ref"] - g["pm25_cal"])**2)), include_groups=False)
)
print("\nDistancias euclídeas por día (primeras filas):")
print(dist_by_day.head())

# === 4. Distancia y RMSE para diferentes ventanas (basadas en tiempo) ===
ventanas = ["30min", "1.5h", "3h", "5h", "7h", "9h"]  # puedes cambiar a las que quieras
resultados = []

for v in ventanas:
    ref_roll  = df_merged["pm25_ref"].rolling(window=v, min_periods=1).mean()
    sens_roll = df_merged["pm25_cal"].rolling(window=v, min_periods=1).mean()
    mask = ~(ref_roll.isna() | sens_roll.isna())
    dif  = ref_roll[mask] - sens_roll[mask]
    n    = int(mask.sum())
    euclid = np.sqrt(np.nansum(dif**2))
    rmse   = np.sqrt(np.nanmean(dif**2))
    resultados.append([v, euclid, rmse, n])

df_results = pd.DataFrame(
    resultados,
    columns=["ventana","euclid_total","rmse","n_puntos"]
).set_index("ventana")

print("\nResumen de distancias por ventana:")
print(df_results)

# === 5. Gráficas ===
plt.figure(figsize=(6,4))
plt.plot(df_results.index, df_results["euclid_total"], marker='o')
plt.xlabel("Ventana")
plt.ylabel("Distancia euclídea total")
plt.title("Distancia total vs ventana de promedio móvil")
