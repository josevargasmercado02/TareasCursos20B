df_sensor = cal[(cal.index >= inicio) & (cal.index <= fin)].copy()

# Re-muestreo en ventanas de 9 horas
ref_resamp = df_ref['PM2.5'].resample("9h").mean()
cal_resamp = df_sensor['pm25'].resample("9h").mean()

# Eliminar información de zona horaria
ref_resamp.index = ref_resamp.index.tz_localize(None)
cal_resamp.index = cal_resamp.index.tz_localize(None)

# Combinar ambos conjuntos de datos
df = pd.concat([ref_resamp, cal_resamp], axis=1, keys=["ref", "df_sensor"])
df = df.dropna()

# Renombrar columnas
df.columns = ["ref_pm25", "cal_pm25"]

# Número de ventanas
n_ventanas = len(df)
